def printLabelZPL(labelZPL, address):
	"""Prints a label from ZPL code string sent to a networked label printer.
	
	Args:
		labelZPL: (string). Label instruction to be sent to Zebra printer.
		address: (string). IP Address for Zebra printer.
		
	Returns:
		address or error message
	"""
	from java.net import Socket
	from java.io import DataOutputStream
	
	port = int(9100)
	
	try:
		# Open Socket Connection and data output stream, send data to printer, and close data stream and socket
		clientSocket = Socket(address, port)
		outToPrinter = DataOutputStream(clientSocket.getOutputStream())
		outToPrinter.write(labelZPL)
		outToPrinter.close()
		clientSocket.close()
		return address
		
	except IOError:
		return 'Printing failed due to IO Error'



def getLabelaryImage(labelZPL, rotation, dpmm=8, labelWidth=4, labelHeight=6):
	"""Calls Labelary API to retrieve an image of a label generated by ZPL code passed into this function.
	
	Args:
		labelZPL: (string). ZPL Label instruction to be sent to Zebra printer, or in this case the Labelary API.
		rotation: (int). degrees to rotate label image after image is generated. Can be 0, 90, 180, or 270.
		dpmm: (int, default=8). label printer resolution in Dots Per Millimeter. Can be 6, 8, 12, or 24. (150, 203, 300, and 600 dpi, respectively)
		labelWidth: (int, default=4). label width in inches.
		labelHeight: (int, default=6). label height in inches.
		
	Returns:
		labelImageString: (string). Base64-encoded string representing the label image returned from Labelary API.
		
	Typical usage example:
		imageSource = exchange.zplLabelPrinting.label.getLabelaryImage(labelZPL, int(labelRotation))
	
	"""
	from java.util import Base64 # the source for the Ignition Perspective Image component can be set to a Base64 encoded image.
	
	# Connect to Labelary API. see https://labelary.com/service.html for reference.
	# Define print density (8 dpmm), label width (4 inches) x label height (6 inches), and label index (0).
	# http://api.labelary.com/v1/printers/{dpmm}dpmm/labels/{width}x{height}/{index}
	url = 'http://api.labelary.com/v1/printers/' + str(dpmm) + 'dpmm/labels/' + str(labelWidth) + 'x' + str(labelHeight) + '/0' 
	headers = {
		'Accept' : 'image/png' 
		, 'Content-Type' : 'application/x-www-form-urlencoded'
		, 'X-Rotation' : rotation
		#, 'X-Total-Count' : 2 # parameter not used
	}
	data = { 'file' : labelZPL }
	
	# post response
	client = system.net.httpClient()
	response = client.post(url, headers=headers, data=data)
	
	# if the response from Labelary is valid (code 200), then encode the image data as base64 for preview and return it. otherwise return a blank string.
	if response.statusCode == 200:
		imageByteArray = response.body # this is a byte array that needs to be base64-encoded
		imageEncoded = Base64.getEncoder().encodeToString(imageByteArray) 
		labelImageString = "data:imagef;base64,%s"%imageEncoded
		
	else:
		system.perspective.print('Error: ' + response.text) 
		labelImageString = ''
	
	return labelImageString



def getLocalImage(labelZPL, rotation, dpi=203, labelWidth=4, labelHeight=6):
	"""Calls internal local scripting functions to retrieve an image of a label generated by ZPL code passed into this function.
	
	Args:
		labelZPL: (string). ZPL Label instruction to be sent to Zebra printer, or in this case the local print preview function.
		rotation: (int). degrees to rotate label image after image is generated. Can be 0, 90, 180, or 270.
		dpi: (int, default=203). label printer resolution in Dots Per Inch. Can be 203, 300, or 600 dpi
		labelWidth: (int, default=4). label width in inches.
		labelHeight: (int, default=6). label height in inches.
		
	Returns:
		labelImageString: (string). Base64-encoded string representing the label image returned from the local scripting functions.
		
	Typical usage example:
		imageSource = exchange.zplLabelPrinting.label.getLocalImage(labelZPL, int(labelRotation))
	
	"""
	labelImage = exchange.zplLabelPrinting.printPreview.drawing.drawBlankLabel(labelWidth, labelHeight, dpi)
	labelFields = exchange.zplLabelPrinting.printPreview.zplParsing.getFieldDicts(labelZPL)
	
	listPO = []
	for fieldDict in labelFields:
		system.perspective.print(fieldDict) 
		
		if 'field_origin_x' in fieldDict:
			x = int(fieldDict['field_origin_x'])
			y = int(fieldDict['field_origin_y'])
			z = int(fieldDict['field_origin_z'])
			f = 'FO'
		elif 'field_typeset_x' in fieldDict:
			x = int(fieldDict['field_typeset_x'])
			y = int(fieldDict['field_typeset_y'])
			z = int(fieldDict['field_typeset_z'])
			f = 'FT'
		else:
			x = 0
			y = 0
			z = 0
			f = ''
		
		if 'graphic_box_w' in fieldDict: # lines or rectangles
			labelImage = exchange.zplLabelPrinting.printPreview.drawing.drawGraphicBox(
				labelImage
				, x, y, z, f
				, int(fieldDict['graphic_box_w'])
				, int(fieldDict['graphic_box_h'])
				, int(fieldDict['graphic_box_t'])
				, str(fieldDict['graphic_box_c'])
				, int(fieldDict['graphic_box_r'])
			)
		elif 'field_block_width' in fieldDict: # multi-line text
			labelImage = exchange.zplLabelPrinting.printPreview.drawing.drawText(
				labelImage
				, str(fieldDict['field_data'])
				, x, y, z, f
				, int(fieldDict['font_width'])
				, int(fieldDict['font_height'])
				, str(fieldDict['font_name'])
				, str(fieldDict['font_orientation'])
				, 'B' # font color black
				, int(fieldDict['field_block_width'])
				, int(fieldDict['field_block_max_lines'])
				, int(fieldDict['field_block_line_space'])
				, str(fieldDict['field_block_justify'])
				, int(fieldDict['field_block_indent'])
			)
		elif 'font_name' in fieldDict: # 1 line text
			labelImage = exchange.zplLabelPrinting.printPreview.drawing.drawText(
				labelImage
				, str(fieldDict['field_data'])
				, x, y, z, f
				, int(fieldDict['font_width'])
				, int(fieldDict['font_height'])
				, str(fieldDict['font_name'])
				, str(fieldDict['font_orientation'])
			)
		elif 'bc_height' in fieldDict: # 1D barcodes
			# the bcHeight determined by ^BY is trumped by the ^BC command if defined
			if fieldDict['bc_height'] != None and fieldDict['bc_height'] != '':
				bcHeight = fieldDict['bc_height']
			else:
				bcHeight = fieldDict['by_height'] # use height in ^BY command
			labelImage = exchange.zplLabelPrinting.printPreview.drawing.drawBarcodePlaceholder(
				labelImage
				, str(fieldDict['field_data'])
				, x, y, z, f
				, int(fieldDict['by_width']) 
				, int(bcHeight)
				, str(fieldDict['bc_orientation'])
			)
		elif 'bc_square' in fieldDict: # 2D barcodes and images
			# the bcHeight determined by ^BY is trumped by the ^BC command if defined
			system.perspective.print(fieldDict)
			labelImage = exchange.zplLabelPrinting.printPreview.drawing.drawBarcodePlaceholder(
				labelImage
				, str(fieldDict['field_data'])
				, x, y, z, f
				, int(fieldDict['bc_square']) # replace by_width with value 100 from class definitions
				, int(fieldDict['bc_square'])
				, str(fieldDict['bc_orientation'])
			)
		
		if 'print_orientation' in fieldDict:
			listPO.append(str(fieldDict['print_orientation']))
	
	# perform rotation. Assume that if ^POI was ever defined, the label was intended to be inverted, since I'm bad at regex
	if 'I' in listPO: 
		rotation = (rotation + 180) % 360 # flip between 90 and 270, or 0 and 180
	rotatedImage = exchange.zplLabelPrinting.printPreview.drawing.rotateImage(labelImage, rotation)
	
	# convert image to base64 string and return it
	imageString = exchange.zplLabelPrinting.printPreview.drawing.convertImageToBase64(rotatedImage)
	return imageString









def getLabelZPL(labelName, itemDescription, gtin, lotNo, expirationYYMMDD):
	"""NOT USED: Example function for passing in data from somewhere into a parametrized label template and returning the updated zpl string. 
	
	Args:
		labelName: (string) name of label template to retrieve from SQL
		itemDescription: (string) description of item that is being labeled
		gtin: (string) GS1 Global Trade Item Number for shipping (e.g. "12345678901234"), 14 digits
		lotNo: (string) Lot number with numeric characters
		expirationYYMMDD: (java date) expiration date in YYMMDD date format 
		
	Returns:
		labelZPL: (string), populated with the inputs above, to be sent to a label printer
		
	Typical usage example:
		labelZPL = exchange.zplLabelPrinting.label.getLabelZPL('GS1-128 Parameterized', 'ZT621 Zebra label printer', '12345678901234', '251231012345', system.date.now())
	
	"""	
	# if we have all the info we need to define the label, we can generate a ZPL string and return it
	expirationYYMMDD = system.date.format(expirationYYMMDD, 'yyMMdd') # GS1 Application Identifier Code is 17
	
	# retrieve the label from SQL, based on the name put into this function. user table is joined for reference only.
	getLabelFromSQL = """
		select t.label_name, t.label_zpl, u.user_name
		from ex_zpl_label_printing.ex_zlp_label_templates as t
		left join ex_zpl_label_printing.ex_zlp_label_users as u on u.ex_zlp_label_templates_id = t.id
		where label_name = ?
	"""
	label_DS = system.db.runPrepQuery(getLabelFromSQL, [labelName], 'ex_zpl_label_printing') 
	
	# if the label does not exist, return a label zpl string that indicates the label does not exist. 
	if label_DS.getRowCount() == 0:
		labelZPL = """^XA^CFA,50^FO100,100^A0B,100,0^FDLabel template does not exist.^FS^XZ"""
		
	else: # otherwise, get the label ZPL from SQL and replace all the bracketed info with the function arguments
		labelZPL = label_DS.getValueAt(0, 'label_zpl')
		labelZPL = labelZPL.replace('[itemDescription]', str(itemDescription))
		labelZPL = labelZPL.replace('[gtin]', str(gtin))
		labelZPL = labelZPL.replace('[lotNo]', str(lotNo))
		labelZPL = labelZPL.replace('[expirationYYMMDD]', str(expirationYYMMDD))
		
	
#	# further processing to get rid of apostrophes
#	splitByApostrophe = labelZPL.split("'")
#	labelZPL = ''
#	for chunk in splitByApostrophe:
#		labelZPL += chunk
	
	return labelZPL


